int main() {
    using namespace vektoryum;
    const auto bytes = make_dynamic_huffman_rgba_png();
    const io::RasterDecodeResult decoded = io::decode_raster(io::RasterFormat::Png, bytes);
    require(decoded.ok(), "real dynamic-Huffman RGBA PNG must decode");
    require(decoded.image.spec.width == 128U && decoded.image.spec.height == 1U,
            "dynamic-Huffman PNG dimensions must match IHDR");
    require(decoded.image.rgba8.size() == 128U * 4U,
            "dynamic-Huffman PNG must produce the full canonical RGBA8 payload");
    for (std::size_t i = 0U; i < 128U; ++i) {
        const std::size_t offset = i * 4U;
        require(decoded.image.rgba8[offset] == static_cast<std::uint8_t>(i), "red sample mismatch");
        require(decoded.image.rgba8[offset + 1U] == static_cast<std::uint8_t>((i * 3U) & 0xffU), "green sample mismatch");
        require(decoded.image.rgba8[offset + 2U] == static_cast<std::uint8_t>((i * 7U) & 0xffU), "blue sample mismatch");
        require(decoded.image.rgba8[offset + 3U] == 255U, "alpha sample mismatch");
    }
    const io::RasterDecodeResult repeat = io::decode_raster(io::RasterFormat::Png, bytes);
    require(repeat.ok() && repeat.image.rgba8 == decoded.image.rgba8,
            "dynamic-Huffman PNG decode must be deterministic");
    return 0;
}
